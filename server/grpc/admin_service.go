// UpdateSnapshotPolicy updates the snapshot retention policy
func (s *AdminServiceServer) UpdateSnapshotPolicy(ctx context.Context, req *proto.UpdateSnapshotPolicyRequest) (*proto.UpdateSnapshotPolicyResponse, error) {
	if err := s.validateAdminToken(req.AdminToken); err != nil {
		return nil, err
	}

	// Update config
	s.config.Snapshots.Schedule.Hourly = int(req.Policy.HourlyRetention)
	s.config.Snapshots.Schedule.Daily = int(req.Policy.DailyRetention)
	s.config.Snapshots.Schedule.Weekly = int(req.Policy.WeeklyRetention)
	s.config.Snapshots.Schedule.Monthly = int(req.Policy.MonthlyRetention)

	// Save config to file
	if err := config.SaveServerConfig(s.config, s.configPath); err != nil {
		log.Printf("Failed to save config: %v", err)
		// Don't fail the request, just log the error
	}

	// Log action
	if err := s.database.LogAction("", "", "snapshot_policy_updated", fmt.Sprintf("Policy: hourly=%d, daily=%d, weekly=%d, monthly=%d",
		req.Policy.HourlyRetention, req.Policy.DailyRetention, req.Policy.WeeklyRetention, req.Policy.MonthlyRetention), ""); err != nil {
		fmt.Printf("WARNING: Failed to log snapshot policy update: %v\n", err)
	}

	return &proto.UpdateSnapshotPolicyResponse{
		Success: true,
		Message: "Snapshot policy updated",
	}, nil
}

// GetSystemStatus returns system status information
func (s *AdminServiceServer) GetSystemStatus(ctx context.Context, req *proto.SystemStatusRequest) (*proto.SystemStatusResponse, error) {
	if err := s.validateAdminToken(req.AdminToken); err != nil {
		return nil, err
	}

	// Get user counts
	allUsers, err := s.database.ListUsers(true)
	if err != nil {
		return nil, status.Error(codes.Internal, "failed to get users")
	}

	activeUsers, err := s.database.ListUsers(false)
	if err != nil {
		return nil, status.Error(codes.Internal, "failed to get active users")
	}

	// Calculate totals
	var totalStorage int64
	var usedStorage int64
	for _, user := range allUsers {
		totalStorage += user.QuotaBytes
		usedStorage += user.UsedBytes
	}

	// Get actual snapshot count
	totalSnapshots, err := s.database.CountAllSnapshots()
	if err != nil {
		log.Printf("Failed to count snapshots: %v", err)
		totalSnapshots = 0
	}

	// Get ZFS pool status
	poolStatus, err := s.zfsManager.GetPoolStatus()
	if err != nil {
		// Log error but don't fail the request
		log.Printf("Failed to get pool status: %v", err)
		poolStatus = &zfs.PoolStatus{
			Name:           s.config.ZFS.Pool,
			TotalBytes:     0,
			UsedBytes:      0,
			AvailableBytes: 0,
			Health:         0.0,
		}
	}

	pools := []*proto.PoolStatus{
		{
			PoolName:       poolStatus.Name,
			TotalBytes:     poolStatus.TotalBytes,
			UsedBytes:      poolStatus.UsedBytes,
			AvailableBytes: poolStatus.AvailableBytes,
			Health:         poolStatus.Health,
		},
	}

	return &proto.SystemStatusResponse{
		TotalUsers:        int64(len(allUsers)),
		ActiveUsers:       int64(len(activeUsers)),
		TotalStorageBytes: totalStorage,
		UsedStorageBytes:  usedStorage,
		TotalSnapshots:    totalSnapshots,
		Pools:             pools,
	}, nil
}

// CreateSnapshot creates a manual snapshot for a specific user
func (s *AdminServiceServer) CreateSnapshot(ctx context.Context, req *proto.CreateSnapshotRequest) (*proto.CreateSnapshotResponse, error) {
	if err := s.validateAdminToken(req.AdminToken); err != nil {
		return nil, err
	}

	// Verify user exists
	user, err := s.database.GetUserByUserID(req.UserId)
	if err != nil {
		return nil, status.Error(codes.NotFound, "user not found")
	}

	// Create snapshot
	snapshotName, sizeBytes, err := snapshot.CreateManualSnapshot(s.database, s.zfsManager, req.UserId)
	if err != nil {
		return nil, status.Errorf(codes.Internal, "failed to create snapshot: %v", err)
	}

	return &proto.CreateSnapshotResponse{
		Success:      true,
		Message:      fmt.Sprintf("Manual snapshot created for user %s", user.UserID),
		SnapshotName: snapshotName,
		SizeBytes:    sizeBytes,
	}, nil
}
